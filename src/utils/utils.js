export function pointInPolygon(polygon, x, y) {
    let result = false;
    for (let i = 0, j = polygon.length - 1; i < polygon.length; i++) {
        if (
            polygon[i][1] > y !== polygon[j][1] > y &&
            x < ((polygon[j][0] - polygon[i][0]) * (y - polygon[i][1])) / (polygon[j][1] - polygon[i][1]) + polygon[i][0]
        ) {
            result = !result;
        }
        j = i;
    }

    return result;
}

export function getPolygonCenter(polygon) {
    let x = 0;
    let y = 0;
    for (let i = 0; i < polygon.length; i++) {
        x += polygon[i][0];
        y += polygon[i][1];
    }

    return { x: x / polygon.length, y: y / polygon.length };
}

export function toPolygon(coordsStr, xRatio, yRatio) {
    if (!coordsStr) {
        return [];
    }
    return coordsStr
        .split(',')
        .map((coord, index, coords) => {
            if (index % 2 === 0) {
                return [parseInt(coord), parseInt(coords[index + 1])];
            }
        })
        .filter((coord) => coord !== undefined)
        .map((coord) => [coord[0] / xRatio, coord[1] / yRatio]);
}

export function getContainedSize(img) {
    var ratio = img.naturalWidth / img.naturalHeight;
    var width = img.height * ratio;
    var height = img.height;
    if (width > img.width) {
        width = img.width;
        height = img.width / ratio;
    }
    return [width, height];
}

export function getRandomPointInCircle(centerX, centerY, radius) {
    const theta = Math.random() * (2 * Math.PI);
    const r = Math.sqrt(Math.random()) * radius;

    const x = centerX + r * Math.cos(theta);
    const y = centerY + r * Math.sin(theta);

    return { x, y };
}

export function formatMillisecondsToTime(milliseconds) {
    // Ensure the input is a number
    if (typeof milliseconds !== 'number' || isNaN(milliseconds)) {
        return 'Invalid input';
    }

    // Calculate hours, minutes, and seconds
    const hrs = Math.floor(milliseconds / 3600000);
    const mins = Math.floor((milliseconds % 3600000) / 60000);
    const secs = Math.floor((milliseconds % 60000) / 1000);

    // Pad with leading zeros if necessary
    const formattedHrs = String(hrs).padStart(2, '0');
    const formattedMins = String(mins).padStart(2, '0');
    const formattedSecs = String(secs).padStart(2, '0');

    return `${formattedHrs}:${formattedMins}:${formattedSecs}`;
}

/**
 * Compact clock for in-game display: 42 → "0:42", 724 → "12:04", 3725 → "1:02:05"
 */
export function formatClock(seconds) {
    const total = Math.max(0, Math.floor(seconds || 0));
    const hrs = Math.floor(total / 3600);
    const mins = Math.floor((total % 3600) / 60);
    const secs = String(total % 60).padStart(2, '0');

    return hrs > 0 ? `${hrs}:${String(mins).padStart(2, '0')}:${secs}` : `${mins}:${secs}`;
}

/**
 * Human duration for cumulated play time: 45 → "45 s", 720 → "12 min", 11520 → "3 h 12"
 */
export function formatDuration(seconds) {
    const total = Math.max(0, Math.floor(seconds || 0));
    if (total < 60) {
        return `${total} s`;
    }
    if (total < 3600) {
        return `${Math.floor(total / 60)} min`;
    }
    return `${Math.floor(total / 3600)} h ${String(Math.floor((total % 3600) / 60)).padStart(2, '0')}`;
}

/**
 * Thumbnail generated by scripts/generate-thumbs.mjs: /images/12.JPEG → /images/thumbs/12.webp
 */
export function thumbUrl(quest) {
    if (!quest?.url) {
        return '';
    }
    return quest.url.replace(/\/([^/]+)\.[^./]+$/, '/thumbs/$1.webp');
}

/**
 * Alex's position in the photo, as percentages of its width and height (polygon center)
 */
export function alexPosition(quest) {
    const polygon = toPolygon(quest?.coords, 1, 1);
    if (!polygon.length || !quest.width || !quest.height) {
        return { x: 50, y: 50 };
    }
    const center = getPolygonCenter(polygon);
    return { x: (center.x / quest.width) * 100, y: (center.y / quest.height) * 100 };
}

/**
 * Ring around Alex once found, as percentages of the photo width and height:
 * a bit wider than his outline, and never too small to be seen without zooming,
 * unless it hugs him (hug), for when the photo zooms in on him
 */
export function alexRing(quest, { hug = false } = {}) {
    const polygon = toPolygon(quest?.coords, 1, 1);
    if (!polygon.length || !quest.width || !quest.height) {
        return null;
    }
    const xs = polygon.map(([x]) => x);
    const ys = polygon.map(([, y]) => y);
    const [left, right, top, bottom] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
    const outline = Math.max(right - left, bottom - top) * 1.4;
    const size = hug ? outline : Math.max(outline, Math.min(quest.width, quest.height) * 0.08);
    return {
        x: ((left + right) / 2 / quest.width) * 100,
        y: ((top + bottom) / 2 / quest.height) * 100,
        width: (size / quest.width) * 100,
        height: (size / quest.height) * 100,
    };
}

